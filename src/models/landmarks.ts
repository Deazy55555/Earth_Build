const ring = (n: number, r: number, f: (x: number, z: number, a: number, i: number) => void) => {
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    f(Math.cos(a) * r, Math.sin(a) * r, (a * 180) / Math.PI, i);
  }
};

